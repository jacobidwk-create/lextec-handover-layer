def _is(name: str, value: str):
    return lambda case: case.value(name) == value


def inheritance_start(case: Case):
    """The day the three months for disclaiming start, by how the person became an
    heir: knowledge of the death (statutory), official notification of the will
    (appointed), knowledge that the inheritance fell to them (successor)."""
    name = {"statutory": "date_learned_of_death", "appointed": "appointment_notice_date",
            "successor": "heir_knowledge_date"}.get(case.value("heir_basis"))
    return case.value(name) if name else None


def disclaimer_state(case: Case) -> str:
    """"open", "passed" or "unknown": whether the three months for disclaiming may have
    passed on the day the case was last assessed (earliest possible end, Art. 567 ZGB)."""
    from datetime import date as _date
    from . import config
    from .deadlines import add_months
    start = inheritance_start(case)
    if start is None:
        return "unknown"
    today = case.assessed_on or _date.today()
    return "passed" if add_months(start, config.DISCLAIMER_MONTHS) < today else "open"


def register_objection_open(case: Case) -> bool:
    """Register entries: True if the ten days from service of the payment order have
    not passed on the day the case was last assessed (earliest possible end, Art. 74
    SchKG) and the person has not said that they raised the objection. The objection
    can then still be declared. It holds as soon as the day of service is known, also
    before the question about the objection is answered, so that the urgent notice is
    not delayed by the order of the questions."""
    from datetime import date as _date, timedelta
    from . import config
    served = case.value("register_service_date")
    if (served is None or case.value("register_entry") != "enforcement"
            or case.value("register_objection") == "yes"
            or case.value("register_payment") == "paid_after"):
        return False
    today = case.assessed_on or _date.today()
    return today <= served + timedelta(days=config.OBJECTION_DAYS)


def register_request_from(case: Case):
    """Register entries: the first day on which the request for non-disclosure can be
    filed, the day after three months from service of the payment order (Art. 8a
    para. 3 lit. d SchKG). None while the day of service is not known."""
    from datetime import timedelta
    from . import config
    from .deadlines import add_months
    served = case.value("register_service_date")
    if served is None:
        return None
    return add_months(served, config.REGISTER_WAIT_MONTHS) + timedelta(days=1)


def register_wait(case: Case) -> str:
    """"over", "running" or "unknown": whether the three months since service of the
    payment order have passed on the day the case was last assessed."""
    from datetime import date as _date
    first = register_request_from(case)
    if first is None:
        return "unknown"
    return "over" if (case.assessed_on or _date.today()) >= first else "running"


def _register_enforcement(case: Case) -> bool:
    return case.value("register_entry") == "enforcement"


def _register_unpaid_or_before(case: Case) -> bool:
    return (_register_enforcement(case)
            and case.value("register_payment") in ("not_paid", "paid_before"))


# Late fees, gate 2: answers about the original bill after which no default can exist.
PRINCIPAL_NOT_IN_DEFAULT = ("paid_on_time", "not_due", "disputed")


# Late fees: letters whose charges are examined at gates 2 and 3. A payment order gets
# the urgent notice and is then examined like a private letter (decision of the legal
# lead, 2026-11-13), so that the person learns which amount to dispute.
EXAMINED_DOCUMENTS = ("reminder", "payment_order")


def _examined(case: Case) -> bool:
    return case.value("document_type") in EXAMINED_DOCUMENTS


def _principal_settles_it(case: Case) -> bool:
    return case.value("principal_status") in PRINCIPAL_NOT_IN_DEFAULT


def _in_default(case: Case) -> bool:
    """Late fees, gate 3: the single charges are examined only for a person in default."""
    return (_examined(case)
            and case.value("principal_status") in ("open", "paid_late")
            and case.value("default_trigger") in ("reminder", "fixed_date"))


