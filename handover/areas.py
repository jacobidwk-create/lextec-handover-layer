def display_value(value, lang: str, name: str | None = None) -> str:
    """One fact value in plain words. A fact answered from a list is shown with the
    wording of the chosen answer."""
    from datetime import date as _date
    spec = FIELD_BY_NAME.get(name) if name else None
    if spec is not None and str(value) in spec.options:
        return spec.options[str(value)][lang]
    if isinstance(value, _date):
        return value.strftime("%d.%m.%Y")
    if isinstance(value, float):
        return f"{value:,.2f}".replace(",", "'")
    return VALUE_LABELS.get(str(value), {}).get(lang, str(value))

