# Areas in which the three general scope questions (canton, several claims, other
# deadlines) are not asked. Late fees are judged by federal contract law and the
# framework asks for nothing else; the rules behind those facts still apply when the
# user mentions them.
NO_COMMON_QUESTIONS = {"debt_collection", "inheritance_debt", "credit_record"}


def required_fields(case: Case) -> list[FieldSpec]:
    """Fields currently required, critical ones first."""
    common = bool(case.areas.keys() - NO_COMMON_QUESTIONS)
    req = [f for f in FIELDS
           if f.ask and (f.area in case.areas or f.area == "common" and common)
           and (f.when is None or f.when(case))]
    priority = {name: i for i, name in enumerate((
        "document_type", "principal_status", "default_trigger",
        "interest_charge", "reminder_fee", "collection_costs",
        "heir_basis", "date_learned_of_death", "appointment_notice_date",
        "heir_knowledge_date", "estate_insolvency", "estate_actions", "estate_finances",
        "register_entry", "register_payment", "register_objection",
        "register_service_date", "register_creditor_step", "register_missed_reason"))}
    return sorted(req, key=lambda f: (priority.get(f.name, 100), not f.critical))


UNKNOWN_CHOICE = "__unknown__"      # the list entry "I do not know"


def needs_confirmation(case: Case, name: str) -> bool:
    """True if the model read a consequential value from free text and the person has
    not confirmed it yet (FieldSpec.confirm)."""
    from .schema import Status
    spec, f = FIELD_BY_NAME.get(name), case.facts.get(name)
    return bool(spec and f and f.status is Status.KNOWN and not f.confirmed
                and f.value in spec.confirm)


def established(case: Case, name: str):
    """The value of a fact that rules may act on: known and, where needed, confirmed."""
    return None if needs_confirmation(case, name) else case.value(name)


def needs_detail(case: Case, name: str) -> bool:
    """True if the fact holds a partial answer ("yes, that is claimed") and the detail
    that decides the outcome has not been asked for yet (FieldSpec.partial)."""
    from .schema import Status
    spec, f = FIELD_BY_NAME.get(name), case.facts.get(name)
    return bool(spec and f and f.status is Status.KNOWN and f.value in spec.partial
                and f.detail_asks < 1)


def options_for(name: str, lang: str, detail: bool = False) -> list[dict]:
    """The answers offered as quick replies: for the first question the simple ones,
    for the follow-up on a partial answer the detail values."""
    spec = FIELD_BY_NAME[name]
    if detail:
        values = spec.detail["values"]
    elif spec.first:
        values = spec.first
    else:
        hidden = set(spec.partial) | set(spec.detail.get("values", ()))
        values = [v for v in spec.choices if v not in hidden]
    return [{"value": v, "label": spec.options[v][lang]} for v in values if v in spec.options]


