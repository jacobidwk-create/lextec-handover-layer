def display_facts(case: Case) -> list[str]:
    """Established facts in plain words, in the user's language."""
    from .schema import Status
    lang, out = case.language, []
    for f in case.facts.values():
        if f.status is not Status.KNOWN or f.name not in LABELS:
            continue
        out.append(f"{LABELS[f.name][lang]}: {display_value(f.value, lang, f.name)}")
    return out


